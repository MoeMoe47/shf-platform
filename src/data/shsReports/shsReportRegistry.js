const commonSections = ["executive-summary", "readiness", "history", "export-metadata"];

function reportType({
  id,
  displayName,
  description,
  allowedSubjectTypes,
  requiredDataSources,
  optionalDataSources = [],
  requiredSections,
  optionalSections = [],
  supportedBrandModes = ["shs-premium"],
  defaultVisibility = "internal-only",
  blockedVisibilityModes = [],
  requiresDataReview = true,
  requiresBrandReview = false,
  requiresAuditReview = false,
  templateVersion = "shs-generic-report-v1",
}) {
  return {
    id,
    displayName,
    description,
    allowedSubjectTypes,
    requiredDataSources,
    optionalDataSources,
    requiredSections,
    optionalSections,
    supportedBrandModes,
    defaultVisibility,
    blockedVisibilityModes,
    lifecycleRequirements: {
      requiresDataReview,
      requiresBrandReview,
      requiresAuditReview,
    },
    exportEligibilityRules: [
      "required_sources_not_missing",
      "required_sections_not_missing",
      "visibility_rules_clear",
      "export_metadata_present",
      requiresDataReview ? "data_review_complete" : "",
      requiresBrandReview ? "brand_review_complete" : "",
      requiresAuditReview ? "audit_review_complete" : "",
    ].filter(Boolean),
    templateVersion,
    requiresDataReview,
    requiresBrandReview,
    requiresAuditReview,
  };
}

