function readiness(overrides = {}) {
  const base = {
    clientops: ["approved", "Client record and health summary available"],
    "reporting-layer": ["draft", "KPI fields require review"],
    "internal-ops": ["approved", "Internal operating context available"],
    "qa-delivery": ["verified", "Delivery checks available"],
    "support-maintenance": ["draft", "Support activity requires final review"],
    "version-history": ["approved", "Recent update records available"],
    "audit-trail": ["draft", "Minor exceptions open"],
    "export-metadata": ["verified", "Report ID and template version available"],
    "sales-handoff": ["sample", "Demo handoff context only"],
    "production-projects": ["approved", "Project status available"],
    "development-library": ["draft", "Build packet source needs review"],
    "brand-profile": ["approved", "Premium OS template alignment confirmed"],
    "data-binding": ["draft", "Data binding rules require review"],
    "mock-review": ["sample", "Mock review sample available"],
    "screenshot-qa": ["draft", "Screenshot QA evidence pending"],
  };

  return Object.entries({ ...base, ...overrides }).map(([sourceArea, [status, notes]]) => ({
    sourceArea,
    label: sourceArea
      .replace(/-/g, " ")
      .replace(/\b\w/g, (char) => char.toUpperCase())
      .replace("Qa", "QA"),
    status,
    lastUpdated: status === "missing" ? "" : "2026-06-21",
    notes,
    requiredForPremium: ["brand-profile", "export-metadata", "audit-trail", "clientops", "reporting-layer"].includes(sourceArea),
    safeForVisibility: !["internal-ops", "audit-trail", "support-maintenance"].includes(sourceArea),
    blockingReason: status === "missing" ? "missing_required_source" : "",
  }));
}

function sections(ids, status = "draft") {
  return ids.map((id) => ({
    id,
    title: id.replace(/-/g, " ").replace(/\b\w/g, (char) => char.toUpperCase()),
    dataStatus: status,
    requiredSources: [],
    isRequired: true,
    visibilitySafe: true,
  }));
}

