function health(overall, overrides = {}) {
  return {
    validation: overall,
    documentation: overall,
    coverage: Math.max(70, overall - 6),
    governance: overall,
    smoke_tests: Math.max(70, overall - 8),
    dependencies: Math.max(70, overall - 5),
    performance: Math.max(70, overall - 10),
    security: overall,
    technical_debt: Math.max(65, overall - 12),
    overall,
    ...overrides,
  };
}

